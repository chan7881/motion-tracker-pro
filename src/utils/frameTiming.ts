// 장면을 뽑을 때 영상의 어느 시각으로 탐색(seek)할지.
//
// 영상의 장면 n은 [n/F, (n+1)/F) 동안 화면에 나온다(F = 영상 FPS). 탐색 시각이 장면 경계에 딱
// 걸리면 브라우저가 앞 장면을 줄지 뒤 장면을 줄지가 반올림에 따라 갈려, 뽑힌 장면들의 간격이
// 고르지 않게 된다(위치가 멈칫거려 속력·가속도가 크게 튄다).
//
// 처음에는 각 구간의 "가운데"(0.5)로 탐색했는데, 영상 FPS가 추출 FPS의 짝수 배일 때(60 fps 영상을
// 30으로, 30 fps 영상을 15로 뽑기 — 가장 흔한 경우) 가운데가 바로 경계다. 실제 60 fps 영상을
// 30으로 뽑았더니 장면이 「예상, 한 장 앞, 한 장 앞」 순서로 되풀이됐다.
// 0.465는 흔한 영상 FPS(24~240)와 추출 FPS(1~60)가 정수배인 모든 조합에서 경계와 0.58 ms 이상
// 떨어진다(아이폰은 장면 시각을 ms로 반올림하므로 0.5 ms보다 멀어야 한다). 0.25~0.5를 0.001 간격으로
// 훑어 가장 멀리 떨어지는 값을 골랐다. 조합 목록은 tests/frameTiming.test.ts에 있다.
export const SAMPLE_PHASE = 0.465;

export function sampleTime(index: number, fps: number): number {
  return (index + SAMPLE_PHASE) / fps;
}
